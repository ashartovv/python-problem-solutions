# Input:
# Declare an anonymous (lambda) function with two parameters
# for dividing the first integer (the first parameter)
# by the second integer (the second parameter).
#
# If division by zero occurs, the function must return None.
# Otherwise, it must return the division result.
#
# Assign this function to the variable get_div.
#
# Do not call the function, only declare it.

get_div = lambda x, y: None if y == 0 else x / y